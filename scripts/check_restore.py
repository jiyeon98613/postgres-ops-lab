"""Regression check with disposable records; no production measurements are produced."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

from common import Cluster, executable_dir, private_root


def main():
    os.umask(0o077)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", required=True)
    parser.add_argument("--pg-bin")
    args = parser.parse_args()
    root = private_root(args.workspace)
    pg_bin = executable_dir(args.pg_bin)
    with Cluster(private_root(str(root / "source")), pg_bin) as source:
        source.create_database("fixture")
        with source.connect("fixture") as conn:
            conn.execute("CREATE SCHEMA sample")
            conn.execute("CREATE TABLE sample.parent (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label text NOT NULL)")
            conn.execute("CREATE TABLE sample.child (id integer PRIMARY KEY, parent_id bigint REFERENCES sample.parent, value jsonb, at timestamptz, note text)")
            conn.execute("CREATE TABLE sample.empty (id integer PRIMARY KEY)")
            conn.execute("INSERT INTO sample.parent (label) VALUES (%s), (%s)", ("검증용\\문자\n탭\t", "second"))
            conn.execute("INSERT INTO sample.child VALUES (1, 1, '{\"key\": [1, null, \"text\"]}', '2026-01-01 09:00:00+09', NULL)")
            conn.execute("CREATE INDEX child_parent ON sample.child(parent_id)")
            conn.execute("CREATE ROLE fixture_reader NOLOGIN")
            conn.execute("ALTER TABLE sample.parent ENABLE ROW LEVEL SECURITY")
            conn.execute("CREATE POLICY fixture_policy ON sample.parent FOR SELECT TO fixture_reader USING (true)")
            conn.execute("CREATE SCHEMA staging")
            conn.execute("""CREATE TABLE staging.change_sets (
                change_set_id uuid PRIMARY KEY, vendor_id uuid NOT NULL,
                change_type varchar(80) NOT NULL, created_at timestamptz NOT NULL,
                deleted_at timestamptz, source_fingerprint varchar(64) NOT NULL,
                processing_stage varchar(30) NOT NULL CHECK (processing_stage IN ('DISCOVERY','EXTRACT')),
                UNIQUE(change_set_id,vendor_id))""")
            conn.execute("""CREATE TABLE staging.change_items (
                change_item_id uuid PRIMARY KEY, change_set_id uuid NOT NULL, vendor_id uuid NOT NULL,
                business_key varchar(300) NOT NULL, created_at timestamptz NOT NULL,
                deleted_at timestamptz, proposed_values jsonb NOT NULL, validation_codes jsonb NOT NULL,
                idempotency_key varchar(64) NOT NULL, review_status varchar(30) NOT NULL,
                UNIQUE(vendor_id,idempotency_key),
                FOREIGN KEY(change_set_id,vendor_id) REFERENCES staging.change_sets(change_set_id,vendor_id))""")
            conn.execute("""INSERT INTO staging.change_sets
                SELECT md5('set-'||i)::uuid, md5('vendor')::uuid, 'PATIENT_DOCUMENT_DISCOVERY',
                '2026-01-01'::timestamptz + i * interval '1 day', NULL, md5('source-'||i), 'DISCOVERY'
                FROM generate_series(1,5) i""")
            conn.execute("""INSERT INTO staging.change_items
                SELECT md5('item-'||i)::uuid, md5('set-'||((i-1)/20+1))::uuid, md5('vendor')::uuid,
                'fixture-file-'||(i%20), '2026-01-01'::timestamptz + i * interval '1 hour', NULL,
                jsonb_build_object('name','fixture-person-'||i,'number',i), '[]'::jsonb, md5('item-'||i), 'PENDING'
                FROM generate_series(1,100) i""")
            conn.execute("CREATE INDEX ix_change_items_vendor_business_created ON staging.change_items(vendor_id,business_key,created_at)")
            conn.execute("CREATE INDEX ix_change_items_set_review ON staging.change_items(change_set_id,review_status)")
            conn.execute("CREATE INDEX ix_change_sets_type_review ON staging.change_sets(change_type)")
        source.run("pg_dump", "-d", "fixture", "-Fc", "-f", root / "fixture.dump", database="fixture")
    subprocess.run([sys.executable, str(Path(__file__).with_name("restore.py")),
                    "--dump", str(root / "fixture.dump"), "--workspace", str(root / "restored"),
                    "--pg-bin", str(pg_bin), "--placeholder-role", "fixture_reader"], check=True)
    with Cluster(private_root(str(root / "restored")), pg_bin) as target:
        with target.connect() as conn:
            assert conn.execute("SELECT nextval('sample.parent_id_seq')").fetchone()[0] == 3
            assert conn.execute("SELECT count(*) FROM sample.child").fetchone()[0] == 1
            assert conn.execute("SELECT count(*) FROM sample.empty").fetchone()[0] == 0
    print("restore regression check passed")
    for script, extra in (("drop_restore.py", []),
                          ("tuning.py", ["--clients", "1", "--transactions", "10", "--rounds", "2"]),
                          ("roles.py", [])):
        with (root / f"{script}.log").open("wb") as log:
            subprocess.run([sys.executable, str(Path(__file__).with_name(script)),
                            "--workspace", str(root / "restored"), "--pg-bin", str(pg_bin), *extra],
                           stdout=log, stderr=log, check=True)
        result_name = {"tuning.py": "tuning-result.json", "roles.py": "roles-result.json",
                       "drop_restore.py": "drop-restore-result.json"}[script]
        result = json.loads((root / "restored" / result_name).read_text())
        assert result["status"] == "passed"
        print(f"{script} regression check passed")
    from tuning import sanitized_plan
    assert "sensitive" not in json.dumps(sanitized_plan([{"Plan": {"Node Type": "Index Scan",
        "Index Cond": "sensitive", "Filter": "sensitive", "New Server Field": "sensitive"}}]))
    with Cluster(private_root(str(root / "restored")), pg_bin) as target:
        with target.connect("query_check") as conn:
            assert not conn.execute("SELECT 1 FROM staging.change_items WHERE proposed_values::text LIKE '%fixture-person-%'").fetchone()
            assert conn.execute("SELECT count(*) FROM staging.change_items").fetchone()[0] == 100
    print("masking and plan-redaction regression checks passed")


if __name__ == "__main__":
    main()
